"""
Verify each CLI distribution carries the surviving skill set in the right shape.

- Codex ships native plugins (two plugins under dist/codex/plugins/, registered by
  the repo-root .agents/plugins/marketplace.json). No installer, no agents, no
  namespacing suffixes.
- OpenCode ships a plugin (dist/opencode/plugin/) that registers the source skill
  directories (claude-plugins/*/skills) via skills.paths and slash-command wrappers
  via cfg.command. No installer, no command files, no copied payload.
- Pi's package manifest (repo-root package.json) points at the same source skill
  directories and ships prompt-template aliases for the main entrypoints; no
  TypeScript runtime extension, no copied payload.
- Codex's plugin directories are byte-identical copies of the source skill
  directories, regenerated by scripts/sync_dist.py and checked for drift here.

Skill text is host-neutral (tests/test_skill_frontmatter.py enforces it), so every
surface reads the same words: no per-host rewrite exists.

Reviewers are dimensions of the review-code skill, not standalone agents.
"""

from __future__ import annotations

