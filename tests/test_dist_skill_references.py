CURSOR_MARKETPLACE = ROOT / ".cursor-plugin" / "marketplace.json"
# The keys Cursor's published schemas accept (additionalProperties is false in both):
# https://github.com/cursor/plugins/blob/main/schemas/plugin.schema.json and
# https://github.com/cursor/plugins/blob/main/schemas/marketplace.schema.json
CURSOR_PLUGIN_KEYS = {
    "name",
    "displayName",
    "description",
    "version",
    "minClientVersions",
    "author",
    "publisher",
    "homepage",
    "repository",
    "license",
    "logo",
    "keywords",
    "category",
    "tags",
    "commands",
    "agents",
    "skills",
    "rules",
    "hooks",
    "variables",
    "mcpServers",
}
CURSOR_MARKETPLACE_KEYS = {"name", "owner", "metadata", "plugins"}
CURSOR_ENTRY_KEYS = {"name", "source", "description", "minClientVersions"}
# What Cursor discovers in a plugin directory besides skills/ when the manifest
# names no path (https://cursor.com/docs/reference/plugins). manifest-dev ships
# skills only, so none of these may appear in a source plugin directory.
CURSOR_OTHER_COMPONENTS = ("rules", "agents", "commands", "hooks", "mcp.json")


def _json(path: Path) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _cursor_entries() -> dict[str, dict[str, Any]]:
    return {e["name"]: e for e in _json(CURSOR_MARKETPLACE)["plugins"]}


def _safe_relative(value: str) -> bool:
    return (
        bool(value)
        and not value.startswith("/")
        and ".." not in Path(value).parts
        and "\\" not in value
    )


# Holds the decision in docs/adr/20261021-cursor-plugin-reads-the-source-plugin-directories.md.
def test_cursor_marketplace_mirrors_the_claude_marketplace() -> None:
    """Cursor lists the same plugins, at the same source directories, as Claude Code."""
    marketplace = _json(CURSOR_MARKETPLACE)
    assert set(marketplace) <= CURSOR_MARKETPLACE_KEYS
    assert marketplace["owner"]["name"]
    claude = {
        e["name"]: Path(e["source"])
        for e in _json(ROOT / ".claude-plugin" / "marketplace.json")["plugins"]
    }
    entries = _cursor_entries()
    assert entries.keys() == claude.keys()
    for name, entry in entries.items():
        assert set(entry) <= CURSOR_ENTRY_KEYS, name
        assert _safe_relative(entry["source"]), entry["source"]
        assert Path(entry["source"]) == claude[name], name


# Holds the decision in docs/adr/20261021-cursor-plugin-reads-the-source-plugin-directories.md.
def test_cursor_plugin_manifests_track_their_source_plugins() -> None:
    """Each Cursor manifest sits beside the Claude one, carries its name and version,
    uses only keys Cursor's schema accepts, and names the metadata a listing needs."""
    for name, entry in _cursor_entries().items():
        plugin_dir = ROOT / entry["source"]
        cursor = _json(plugin_dir / ".cursor-plugin" / "plugin.json")
        source = _json(plugin_dir / ".claude-plugin" / "plugin.json")
        assert set(cursor) <= CURSOR_PLUGIN_KEYS, sorted(
            set(cursor) - CURSOR_PLUGIN_KEYS
        )
        assert cursor["name"] == source["name"] == name
        assert cursor["version"] == source["version"], name
        assert re.fullmatch(r"\d+\.\d+\.\d+", cursor["version"])
        for field in ("description", "license", "repository", "logo"):
            assert cursor.get(field), f"{name}: {field}"
        assert cursor["author"]["name"]
        logo = cursor["logo"]
        if logo.startswith(
            "https://raw.githubusercontent.com/doodledood/manifest-dev/"
        ):
            assert (ROOT / logo.split("/", 6)[6]).is_file(), logo
        else:
            assert _safe_relative(logo) and (plugin_dir / logo).is_file(), logo


# Holds the decision in docs/adr/20261021-cursor-plugin-reads-the-source-plugin-directories.md.
def test_cursor_discovers_the_source_skills_with_no_copy() -> None:
    """No manifest overrides discovery, so Cursor reads claude-plugins/<plugin>/skills;
    nothing else Cursor would load sits in a source plugin, and dist/cursor holds docs only.
    """
    expected = {"manifest-dev": CORE_SKILLS, "manifest-dev-tools": TOOLS_SKILLS}
    for name, entry in _cursor_entries().items():
        plugin_dir = ROOT / entry["source"]
        cursor = _json(plugin_dir / ".cursor-plugin" / "plugin.json")
        for component in (
            "skills",
            "rules",
            "agents",
            "commands",
            "hooks",
            "mcpServers",
        ):
            assert component not in cursor, f"{name}: {component} overrides discovery"
        for other in CURSOR_OTHER_COMPONENTS:
            assert not (plugin_dir / other).exists(), f"{name}: {other}"
        discovered = tuple(
            sorted(
                p.name
                for p in (plugin_dir / "skills").iterdir()
                if (p / "SKILL.md").is_file()
            )
        )
        assert discovered == expected[name]
    assert {p.name for p in (DIST / "cursor").iterdir()} == {"README.md"}


