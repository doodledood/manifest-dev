# Malformed activation forms that read as a plugin name followed by a skill name —
# they resolve nowhere and must never appear on any surface.
_MALFORMED_FORMS = ("manifest-dev check-pr skill",)  # space form


def _skill_markdowns(*roots: Path) -> list[Path]:
    return [p for root in roots for p in root.rglob("*.md")]


