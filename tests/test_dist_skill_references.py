def source_skills(plugin: str) -> tuple[str, ...]:
    skills_dir = ROOT / "claude-plugins" / plugin / "skills"
    return tuple(
        sorted(
            path.name
            for path in skills_dir.iterdir()
            if path.is_dir() and (path / "SKILL.md").is_file()
        )
    )


CORE_SKILLS = source_skills("manifest-dev")
TOOLS_SKILLS = source_skills("manifest-dev-tools")
ALL_SKILLS = CORE_SKILLS + TOOLS_SKILLS
PI_PROMPTS = ("do", "auto", "babysit-pr")

CODE_REVIEW_DIMENSIONS = {
    "change-intent",
    "code-bugs",
    "code-design",
    "code-maintainability",
    "code-simplicity",
    "code-testability",
    "context-file-adherence",
    "defect-class",
    "contracts",
    "docs",
    "operational-readiness",
    "prose-value",
    "test-quality",
    "type-safety",
}
RETIRED_REVIEWER_AGENTS = {f"{d}-reviewer" for d in CODE_REVIEW_DIMENSIONS}
REMOVED_SKILLS = ("verify",)

# The superseded manifest schema gave a gate a `verify:` block (carrying
# `instructions`/`prompt`/`model`) and an optional integer `phase`. Both are
# retired: a gate is now a title, a body, an optional why, and a required
# `kind`. Nothing distributed may reintroduce either field.
RETIRED_GATE_FIELDS = re.compile(r"^[ \t]*(?:verify|phase):", re.MULTILINE)

# A gate example in shipped docs: an `AC-`/`INV-G` heading whose block closes on
# a kind declaration (or the schema template's placeholder for one).
GATE_EXAMPLE_HEADING = re.compile(r"^#{3,4} (?:AC-|INV-G)")
GATE_KIND_LINE = re.compile(
    r"^(?:Judgment|Deterministic|\[Judgment \| Deterministic\]) gate\.$"
)

SELF_INDEPENDENCE_CLAIMS = (
    re.compile(
        r"\bindependent(?:ly)?(?:\s+verified)?\s+"
        r"self(?:[- ]verification|\s+mode)\b",
        re.IGNORECASE,
    ),
    re.compile(
        r"\bself(?:[- ]verification|\s+mode)\b"
        r"[^.;\n]{0,100}\b"
        r"(?:is|uses|employs|launches|invokes|has|gets|receives|requires|"
        r"relies\s+on|(?:is\s+)?(?:performed|evaluated|verified)\s+by)\b"
        r"[^.;\n]{0,80}\b(?:an?\s+)?independent(?:ly)?\b",
        re.IGNORECASE,
    ),
)


def claims_self_verification_is_independent(text: str) -> bool:
    normalized = text.replace("`", "")
    for claim in SELF_INDEPENDENCE_CLAIMS:
        for match in claim.finditer(normalized):
            if not re.search(
                r"\b(?:no|not|never|without)\b|non-independent",
                match.group(0),
                re.IGNORECASE,
            ):
                return True
    return False


